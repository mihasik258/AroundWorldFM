LANGUAGE_PREFIXES: tuple[tuple[str, str], ...] = (
    ("español", "spanish"),
    ("espanol", "spanish"),
    ("portugu", "portuguese"),
)

LANGUAGE_SEPARATORS = re.compile(r"\s*[,،/;|&+]\s*|\s+-\s+|\s+and\s+")


def _canonical(value: str) -> str | None:
    if value in LANGUAGE_ALIASES:
        return LANGUAGE_ALIASES[value]
    if value in KNOWN_LANGUAGES:
        return value
    for prefix, canonical in LANGUAGE_PREFIXES:
        if value.startswith(prefix):
            return canonical
    return None


