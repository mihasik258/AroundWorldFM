def normalize_language(raw: str | None) -> str | None:
    if raw is None:
        return None
    value = " ".join(raw.strip().lower().lstrip("#").split())
    if not value:
        return None
    if value in LANGUAGE_ALIASES or value in KNOWN_LANGUAGES:
        return _canonical(value)
    for part in LANGUAGE_SEPARATORS.split(value):
        found = _canonical(part.strip(" .#()"))
        if found:
            return found
    return None


def resolve_coordinates(
    country: str | None, lat: float | None, lon: float | None
) -> tuple[float | None, float | None]:
    if lat is None or lon is None:
        return None, None
    if (lat, lon) != PLACEHOLDER_COORDS:
        return lat, lon
    return COUNTRY_CAPITALS.get(country or "", (None, None))
